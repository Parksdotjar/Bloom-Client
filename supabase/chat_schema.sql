create or replace function public.chat_send_friend_request(p_target_profile_id text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  target_profile_id text;
  pair_low text;
  pair_high text;
  existing_pending_id uuid;
  request_id uuid;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  target_profile_id := nullif(btrim(p_target_profile_id), '');
  if target_profile_id is null then
    raise exception 'Target profile is required.';
  end if;

  if target_profile_id = actor_profile_id then
    raise exception 'You cannot friend yourself.';
  end if;

  if not exists (select 1 from public.chat_profiles cp where cp.mc_profile_id = target_profile_id) then
    raise exception 'Target profile does not exist.';
  end if;

  pair_low := least(actor_profile_id, target_profile_id);
  pair_high := greatest(actor_profile_id, target_profile_id);

  if exists (
    select 1 from public.chat_friendships f
    where f.profile_low = pair_low and f.profile_high = pair_high
  ) then
    raise exception 'Already friends.';
  end if;

  select fr.id into existing_pending_id
  from public.chat_friend_requests fr
  where fr.status = 'pending'
    and least(fr.sender_profile_id, fr.receiver_profile_id) = pair_low
    and greatest(fr.sender_profile_id, fr.receiver_profile_id) = pair_high
  limit 1;

  if existing_pending_id is not null then
    return existing_pending_id;
  end if;

  insert into public.chat_friend_requests (sender_profile_id, receiver_profile_id)
  values (actor_profile_id, target_profile_id)
  returning id into request_id;

  insert into public.chat_notifications (profile_id, type, title, body, payload)
  select
    target_profile_id,
    'friend_request',
    'Friend request',
    cp.mc_username || ' sent you a friend request.',
    jsonb_build_object(
      'request_id', request_id,
      'sender_profile_id', actor_profile_id,
      'sender_username', cp.mc_username
    )
  from public.chat_profiles cp
  where cp.mc_profile_id = actor_profile_id;

  return request_id;
end;
$$;

create or replace function public.chat_respond_friend_request(p_request_id uuid, p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  req public.chat_friend_requests;
  next_status text;
  pair_low text;
  pair_high text;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  next_status := lower(coalesce(p_action, ''));
  if next_status not in ('accepted', 'declined') then
    raise exception 'Action must be accepted or declined.';
  end if;

  select * into req
  from public.chat_friend_requests fr
  where fr.id = p_request_id
  for update;

  if req.id is null then
    raise exception 'Friend request not found.';
  end if;

  if req.receiver_profile_id <> actor_profile_id then
    raise exception 'Not allowed to respond to this request.';
  end if;

  if req.status <> 'pending' then
    return;
  end if;

  update public.chat_friend_requests fr
  set
    status = next_status,
    responded_at = timezone('utc', now())
  where fr.id = req.id;

  if next_status = 'accepted' then
    pair_low := least(req.sender_profile_id, req.receiver_profile_id);
    pair_high := greatest(req.sender_profile_id, req.receiver_profile_id);
    insert into public.chat_friendships (profile_low, profile_high)
    values (pair_low, pair_high)
    on conflict do nothing;
  end if;

  insert into public.chat_notifications (profile_id, type, title, body, payload)
  select
    req.sender_profile_id,
    'friend_request_' || next_status,
    'Friend request ' || next_status,
    cp.mc_username || ' ' || case when next_status = 'accepted' then 'accepted' else 'declined' end || ' your friend request.',
    jsonb_build_object(
      'request_id', req.id,
      'receiver_profile_id', req.receiver_profile_id,
      'receiver_username', cp.mc_username,
      'status', next_status
    )
  from public.chat_profiles cp
  where cp.mc_profile_id = req.receiver_profile_id;
end;
$$;

