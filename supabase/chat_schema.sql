  end if;

  safe_limit := greatest(1, least(coalesce(p_limit, 200), 300));

  return query
  select
    m.id,
    m.thread_id,
    m.sender_profile_id,
    sender.mc_username as sender_username,
    sender.avatar_url as sender_avatar_url,
    m.body,
    m.reply_to_message_id,
    reply_msg.body as reply_body,
    reply_msg.sender_profile_id as reply_sender_profile_id,
    reply_sender.mc_username as reply_sender_username,
    m.edited_at,
    m.deleted_at,
