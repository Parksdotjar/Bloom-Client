create or replace function public.chat_enforce_member_rules()
returns trigger
language plpgsql
as $$
declare
  thread_kind text;
  current_members integer;
begin
  select t.kind into thread_kind
  from public.chat_threads t
  where t.id = new.thread_id
  for update;

  if thread_kind is null then
    raise exception 'Thread not found.';
  end if;

  select count(*)::int into current_members
  from public.chat_thread_members tm
  where tm.thread_id = new.thread_id;

  if thread_kind = 'group' and current_members >= 10 then
    raise exception 'Group chat member limit reached (max 10).';
  end if;

  if thread_kind = 'dm' and current_members >= 2 then
    raise exception 'DM can only contain two members.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_chat_enforce_member_rules on public.chat_thread_members;
create trigger trg_chat_enforce_member_rules
before insert on public.chat_thread_members
for each row
execute procedure public.chat_enforce_member_rules();

create or replace function public.chat_validate_reply_target()
returns trigger
language plpgsql
as $$
declare
  reply_thread_id uuid;
begin
  if new.reply_to_message_id is null then
    return new;
  end if;

  select m.thread_id into reply_thread_id
  from public.chat_messages m
  where m.id = new.reply_to_message_id;

  if reply_thread_id is null then
    raise exception 'Reply target does not exist.';
  end if;

  if reply_thread_id <> new.thread_id then
    raise exception 'Reply target must be from the same thread.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_chat_validate_reply_target on public.chat_messages;
create trigger trg_chat_validate_reply_target
before insert or update of reply_to_message_id, thread_id on public.chat_messages
for each row
execute procedure public.chat_validate_reply_target();

create or replace function public.chat_refresh_thread_timestamps()
returns trigger
language plpgsql
as $$
declare
  affected_thread_id uuid;
  next_last_message_at timestamptz;
begin
  affected_thread_id := coalesce(new.thread_id, old.thread_id);

  select max(m.created_at) into next_last_message_at
  from public.chat_messages m
  where m.thread_id = affected_thread_id;

  update public.chat_threads t
  set
    last_message_at = next_last_message_at,
    updated_at = timezone('utc', now())
  where t.id = affected_thread_id;

  return coalesce(new, old);
end;
$$;

drop trigger if exists trg_chat_refresh_thread_timestamps on public.chat_messages;
create trigger trg_chat_refresh_thread_timestamps
after insert or update or delete on public.chat_messages
for each row
execute procedure public.chat_refresh_thread_timestamps();

create or replace function public.chat_validate_read_receipt()
returns trigger
language plpgsql
as $$
declare
  read_thread_id uuid;
begin
  if new.last_read_message_id is not null then
    select m.thread_id into read_thread_id
    from public.chat_messages m
    where m.id = new.last_read_message_id;

    if read_thread_id is null then
      raise exception 'Read receipt references a missing message.';
    end if;

    if read_thread_id <> new.thread_id then
      raise exception 'Read receipt message must belong to the same thread.';
    end if;
  end if;

  if tg_op = 'UPDATE' and old.last_read_message_id is not null and new.last_read_message_id is not null then
    if new.last_read_message_id < old.last_read_message_id then
      new.last_read_message_id := old.last_read_message_id;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_chat_validate_read_receipt on public.chat_read_receipts;
create trigger trg_chat_validate_read_receipt
before insert or update on public.chat_read_receipts
for each row
execute procedure public.chat_validate_read_receipt();

