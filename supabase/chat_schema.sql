declare
  existing_job record;
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    for existing_job in
      select j.jobid
      from cron.job j
      where j.jobname = 'chat_maintenance_10m'
    loop
      perform cron.unschedule(existing_job.jobid);
    end loop;

    perform cron.schedule(
      'chat_maintenance_10m',
      '*/10 * * * *',
      $cron$select public.chat_run_maintenance();$cron$
    );
  else
    raise notice 'pg_cron extension unavailable. Run SELECT public.chat_run_maintenance(); periodically.';
  end if;
end $$;

