create table if not exists public.chat_threads (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('group', 'dm')),
  title text,
  dm_member_a text references public.chat_profiles(mc_profile_id) on delete set null,
  dm_member_b text references public.chat_profiles(mc_profile_id) on delete set null,
  created_by_profile_id text not null references public.chat_profiles(mc_profile_id) on delete restrict,
  last_message_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint chat_threads_kind_shape_check check (
    (kind = 'dm' and title is null and dm_member_a is not null and dm_member_b is not null and dm_member_a < dm_member_b)
    or
    (kind = 'group' and dm_member_a is null and dm_member_b is null and title is not null and char_length(btrim(title)) between 1 and 80)
  )
);

create unique index if not exists chat_threads_dm_pair_unique_idx
  on public.chat_threads (dm_member_a, dm_member_b)
  where kind = 'dm';

create index if not exists chat_threads_updated_at_idx on public.chat_threads (updated_at desc);
create index if not exists chat_threads_last_message_at_idx on public.chat_threads (last_message_at desc nulls last);

