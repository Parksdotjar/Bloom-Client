create or replace function public.chat_mark_thread_read(p_thread_id uuid, p_message_id bigint default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  resolved_message_id bigint;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  if not exists (
    select 1
    from public.chat_thread_members tm
    where tm.thread_id = p_thread_id
      and tm.member_profile_id = actor_profile_id
  ) then
    raise exception 'Not authorized for this thread.';
  end if;

  if p_message_id is null then
    select max(m.id) into resolved_message_id
    from public.chat_messages m
    where m.thread_id = p_thread_id;
  else
    resolved_message_id := p_message_id;
  end if;

  if resolved_message_id is null then
    return;
  end if;

  if not exists (
    select 1
    from public.chat_messages m
    where m.id = resolved_message_id
      and m.thread_id = p_thread_id
  ) then
    raise exception 'Message is not part of this thread.';
  end if;

  insert into public.chat_read_receipts (thread_id, profile_id, last_read_message_id, last_read_at)
  values (p_thread_id, actor_profile_id, resolved_message_id, timezone('utc', now()))
  on conflict (thread_id, profile_id) do update
  set
    last_read_message_id = greatest(coalesce(public.chat_read_receipts.last_read_message_id, 0), excluded.last_read_message_id),
    last_read_at = timezone('utc', now());
end;
$$;

