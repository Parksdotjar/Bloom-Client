  values (actor_profile_id, coalesce(p_is_online, false), timezone('utc', now()))
  on conflict (mc_profile_id) do update
  set
    is_online = coalesce(p_is_online, false),
    last_seen_at = timezone('utc', now()),
    updated_at = timezone('utc', now());
end;
$$;

create or replace function public.chat_search_profiles(p_query text, p_limit integer default 20)
returns table (
  mc_profile_id text,
  mc_username text,
  avatar_url text,
  is_online boolean,
  last_seen_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  normalized_query text;
  safe_limit integer;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  normalized_query := coalesce(btrim(p_query), '');
  safe_limit := greatest(1, least(coalesce(p_limit, 20), 50));

  return query
  select
    cp.mc_profile_id,
    cp.mc_username,
    cp.avatar_url,
    coalesce(pr.is_online, false) as is_online,
    pr.last_seen_at
  from public.chat_profiles cp
  left join public.chat_presence pr on pr.mc_profile_id = cp.mc_profile_id
  where cp.mc_profile_id <> actor_profile_id
    and (
      normalized_query = ''
      or cp.mc_username ilike normalized_query || '%'
      or cp.mc_username ilike '%' || normalized_query || '%'
    )
  order by
    case when cp.mc_username ilike normalized_query || '%' then 0 else 1 end,
    lower(cp.mc_username)
  limit safe_limit;
end;
$$;

create or replace function public.chat_create_dm(p_target_profile_id text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  target_profile_id text;
  pair_a text;
  pair_b text;
  existing_thread_id uuid;
  created_thread_id uuid;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  target_profile_id := nullif(btrim(p_target_profile_id), '');
  if target_profile_id is null then
    raise exception 'Target profile is required.';
  end if;

  if actor_profile_id = target_profile_id then
    raise exception 'Cannot create a DM with yourself.';
  end if;

  if not exists (
    select 1 from public.chat_profiles cp where cp.mc_profile_id = target_profile_id
  ) then
    raise exception 'Target profile does not exist.';
  end if;

  pair_a := least(actor_profile_id, target_profile_id);
  pair_b := greatest(actor_profile_id, target_profile_id);

  select t.id into existing_thread_id
  from public.chat_threads t
  where t.kind = 'dm'
    and t.dm_member_a = pair_a
    and t.dm_member_b = pair_b
  limit 1;

  if existing_thread_id is not null then
    return existing_thread_id;
  end if;

  insert into public.chat_threads (kind, title, dm_member_a, dm_member_b, created_by_profile_id)
  values ('dm', null, pair_a, pair_b, actor_profile_id)
  returning id into created_thread_id;

  insert into public.chat_thread_members (thread_id, member_profile_id, role)
  values
    (created_thread_id, actor_profile_id, 'owner'),
    (created_thread_id, target_profile_id, 'member')
  on conflict do nothing;

  return created_thread_id;
end;
$$;

create or replace function public.chat_create_group(p_title text, p_member_profile_ids text[])
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  normalized_title text;
  unique_members text[];
  all_members text[];
  known_member_count integer;
  created_thread_id uuid;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  normalized_title := btrim(coalesce(p_title, ''));
  if char_length(normalized_title) < 1 or char_length(normalized_title) > 80 then
    raise exception 'Group title must be between 1 and 80 characters.';
  end if;

  select coalesce(array_agg(distinct btrim(x)), '{}') into unique_members
  from unnest(coalesce(p_member_profile_ids, '{}')) as x
  where btrim(x) <> ''
    and btrim(x) <> actor_profile_id;

  all_members := array_prepend(actor_profile_id, unique_members);

  if cardinality(all_members) < 2 then
    raise exception 'A group chat must include at least two members.';
  end if;

  if cardinality(all_members) > 10 then
    raise exception 'Group chat member limit reached (max 10).';
  end if;

  select count(*)::int into known_member_count
  from public.chat_profiles cp
  where cp.mc_profile_id = any(all_members);

  if known_member_count <> cardinality(all_members) then
    raise exception 'One or more selected members do not exist.';
  end if;

  insert into public.chat_threads (kind, title, created_by_profile_id)
  values ('group', normalized_title, actor_profile_id)
  returning id into created_thread_id;

  insert into public.chat_thread_members (thread_id, member_profile_id, role)
  select
    created_thread_id,
    member_id,
    case when member_id = actor_profile_id then 'owner' else 'member' end
  from unnest(all_members) as member_id;

  return created_thread_id;
end;
$$;

create or replace function public.chat_list_threads()
returns table (
  thread_id uuid,
  kind text,
  title text,
  dm_other_profile_id text,
  dm_other_username text,
  dm_other_avatar_url text,
  member_count integer,
  last_message_id bigint,
  last_message_body text,
  last_message_sender_profile_id text,
  last_message_created_at timestamptz,
  last_message_deleted_at timestamptz,
  last_read_message_id bigint,
  unread_count integer,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  return query
  with actor_threads as (
    select tm.thread_id
    from public.chat_thread_members tm
    where tm.member_profile_id = actor_profile_id
  )
  select
    t.id as thread_id,
    t.kind,
    t.title,
    case when t.kind = 'dm' then other_profile.mc_profile_id else null end as dm_other_profile_id,
    case when t.kind = 'dm' then other_profile.mc_username else null end as dm_other_username,
    case when t.kind = 'dm' then other_profile.avatar_url else null end as dm_other_avatar_url,
    member_stats.member_count,
    lm.id as last_message_id,
    lm.body as last_message_body,
    lm.sender_profile_id as last_message_sender_profile_id,
    lm.created_at as last_message_created_at,
    lm.deleted_at as last_message_deleted_at,
    rr.last_read_message_id,
    coalesce((
      select count(*)::int
      from public.chat_messages unread
      where unread.thread_id = t.id
        and unread.id > coalesce(rr.last_read_message_id, 0)
        and unread.sender_profile_id <> actor_profile_id
        and unread.deleted_at is null
    ), 0) as unread_count,
    t.updated_at
  from actor_threads at
  join public.chat_threads t on t.id = at.thread_id
  left join lateral (
    select cp.mc_profile_id, cp.mc_username, cp.avatar_url
    from public.chat_thread_members tm
    join public.chat_profiles cp on cp.mc_profile_id = tm.member_profile_id
    where tm.thread_id = t.id
      and tm.member_profile_id <> actor_profile_id
    order by tm.joined_at asc
    limit 1
  ) other_profile on true
  left join lateral (
    select count(*)::int as member_count
    from public.chat_thread_members tm
    where tm.thread_id = t.id
  ) member_stats on true
  left join lateral (
    select
      m.id,
      m.body,
      m.sender_profile_id,
      m.created_at,
      m.deleted_at
    from public.chat_messages m
    where m.thread_id = t.id
      and m.created_at >= timezone('utc', now()) - interval '30 days'
    order by m.id desc
    limit 1
  ) lm on true
  left join public.chat_read_receipts rr
    on rr.thread_id = t.id
   and rr.profile_id = actor_profile_id
  order by coalesce(lm.created_at, t.updated_at) desc;
end;
$$;

create or replace function public.chat_list_messages(p_thread_id uuid, p_limit integer default 200)
