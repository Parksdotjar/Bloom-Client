  deleted_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_profile_id text;
  safe_limit integer;
begin
  actor_profile_id := public.chat_actor_profile_id();
  if actor_profile_id is null then
    raise exception 'Chat identity not synced.';
  end if;

  if not exists (
