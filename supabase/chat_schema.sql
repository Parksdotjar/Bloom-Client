do $$
declare
  tbl text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach tbl in array array[
      'chat_threads',
      'chat_thread_members',
      'chat_messages',
      'chat_message_reactions',
      'chat_read_receipts',
      'chat_typing_states',
      'chat_presence',
      'chat_profiles',
      'chat_friendships',
      'chat_friend_requests',
      'chat_notifications'
    ]
    loop
      if not exists (
        select 1
        from pg_publication_tables ppt
        where ppt.pubname = 'supabase_realtime'
          and ppt.schemaname = 'public'
          and ppt.tablename = tbl
      ) then
        execute format('alter publication supabase_realtime add table public.%I', tbl);
      end if;
    end loop;
  else
    raise notice 'supabase_realtime publication not found; realtime table registration skipped.';
  end if;
end $$;

