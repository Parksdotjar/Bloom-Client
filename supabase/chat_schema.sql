create or replace function public.chat_sync_identity(
  p_mc_profile_id text,
  p_mc_username text,
  p_avatar_url text default null
)
returns public.chat_profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  current_uid uuid;
  existing_owner uuid;
  upserted_profile public.chat_profiles;
begin
  current_uid := auth.uid();
  if current_uid is null then
    raise exception 'Authentication required.';
  end if;

  if p_mc_profile_id is null or char_length(btrim(p_mc_profile_id)) = 0 then
    raise exception 'MC profile id is required.';
  end if;

  if p_mc_username is null or char_length(btrim(p_mc_username)) = 0 then
    raise exception 'MC username is required.';
  end if;

  select cp.owner_auth_uid into existing_owner
  from public.chat_profiles cp
  where cp.mc_profile_id = p_mc_profile_id
  limit 1;

  if existing_owner is not null and existing_owner <> current_uid then
    raise exception 'This Minecraft profile is already linked to a different account.';
  end if;

  insert into public.chat_profiles (mc_profile_id, owner_auth_uid, mc_username, avatar_url)
  values (p_mc_profile_id, current_uid, btrim(p_mc_username), nullif(btrim(p_avatar_url), ''))
  on conflict (owner_auth_uid) do update
  set
    mc_profile_id = excluded.mc_profile_id,
    mc_username = excluded.mc_username,
    avatar_url = excluded.avatar_url,
    updated_at = timezone('utc', now())
  returning * into upserted_profile;

  insert into public.chat_presence (mc_profile_id, is_online, last_seen_at)
  values (upserted_profile.mc_profile_id, true, timezone('utc', now()))
  on conflict (mc_profile_id) do update
  set
    is_online = true,
    last_seen_at = timezone('utc', now()),
    updated_at = timezone('utc', now());

  return upserted_profile;
end;
$$;

create or replace function public.chat_set_presence(p_is_online boolean)
